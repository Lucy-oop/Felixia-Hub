const DICTS: Record<Lang, Dict> = { en, ja, my };
const KEY = "felixia-lang";

type Vars = Record<string, string | number>;
type I18n = { lang: Lang; setLang: (l: Lang) => void; t: (k: TKey | string, vars?: Vars) => string; locale: string };
const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    // ?lang=my|en|ja in the URL wins (handy for sharing a link), then the saved choice
    const fromUrl = new URLSearchParams(window.location.search).get("lang") as Lang | null;
    if (fromUrl && fromUrl in DICTS) {
      setLangState(fromUrl);
      return;
    }
    try {
      const saved = localStorage.getItem(KEY) as Lang | null;
      if (saved && saved in DICTS) setLangState(saved);
    } catch {}
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(KEY, l);
    } catch {}
  }, []);

  // unknown keys (e.g. a database error message) are shown as-is
  const t = useCallback(
    (k: string, vars?: Vars) => {
      let out = (DICTS[lang] as Record<string, string>)[k] ?? (en as Record<string, string>)[k] ?? k;
      if (vars) for (const [name, v] of Object.entries(vars)) out = out.replaceAll(`{${name}}`, String(v));
      return out;
    },
    [lang],
  );

  return <Ctx.Provider value={{ lang, setLang, t, locale: LOCALE[lang] }}>{children}</Ctx.Provider>;
}

export function useT() {
  const v = useContext(Ctx);
  if (!v) throw new Error("useT outside I18nProvider");
  return v;
}
